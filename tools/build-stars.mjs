// Packs a star catalogue into src/data/stars.js (base64 Int16 quadruples:
// RA*90, Dec*300, mag*1000, B-V*1000). Input: the JSON produced by Star Sky's
// build-data tool (Yale Bright Star Catalogue, 5th rev. ed.).
//
//   node tools/build-stars.mjs ../Star-Sky/data/stars.json
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2] || '../Star-Sky/data/stars.json';
const d = JSON.parse(readFileSync(src, 'utf8'));
const n = d.ra.length;
const buf = new Int16Array(n * 4);
for (let i = 0; i < n; i++) {
  buf[i * 4] = Math.round(d.ra[i] * 90);
  buf[i * 4 + 1] = Math.round(d.dec[i] * 300);
  buf[i * 4 + 2] = Math.round(d.mag[i] * 1000);
  buf[i * 4 + 3] = Math.round((d.bv[i] ?? 0.6) * 1000);
}
const b64 = Buffer.from(buf.buffer).toString('base64');
writeFileSync(
  new URL('../src/data/stars.js', import.meta.url),
  `// Generated by tools/build-stars.mjs. ${n} stars from the Yale Bright Star\n` +
    `// Catalogue, 5th revised ed. (Hoffleit & Warren 1991). Int16 quadruples:\n` +
    `// RA*90, Dec*300, V mag*1000, (B-V)*1000; J2000.\n` +
    `export const STAR_COUNT = ${n};\nexport const STARS_B64 =\n  '${b64}';\n`,
);
console.log(`packed ${n} stars, ${b64.length} base64 chars`);
